for locale, new_keys in locales.items():
    filepath = f'messages/{locale}.json'
    with open(filepath, 'r') as f:
        data = json.load(f)

    # Merge new keys into existing data
    for key, value in new_keys.items():
        if key in data and isinstance(data[key], dict):
            data[key].update(value)
        else:
            data[key] = value

    with open(filepath, 'w') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

    key_count = sum(len(v) if isinstance(v, dict) else 1 for v in new_keys.values())
    print(f"✅ {locale}: added {key_count} keys across {len(new_keys)} namespaces")

